/* kirikae.js — ★切り替え＝見る人・見る月を 変える（増えない）★
 * =============================================================================
 * ★司さんの言葉（2026-08-28）★「綺麗な形で切り替えれるん？」
 *   ⇒ ★切り出し（新しいシートに出す）とは 別物★
 *      切り替え … ★見る人・見る月を 変える★（★シートは1枚も増えない★）
 *      切り出し … ★新しいシートに 出す★（紙にする・人に渡す・保存する時に要る／今のまま残す）
 *
 * ★決まり★
 *   ・★元の表は 1セルも 触らない★＝ここは「隠す行・隠す列」を 返すだけ。
 *     （画面が sheet.kirikaeRows / kirikaeCols に置く＝★中身ではなく 見え方★）
 *   ・★人が手で隠した行（hiddenRows）／絞り込み（filterHidden）とは 別の入れ物★
 *     ＝戻した時に 相手の分まで 戻してしまわない（実Excelでも 別物として持っている）
 *   ・★期間の決め方は lib/kikan.js（Timeally から借りた物）だけ★＝2つ目を作らない
 *   ・★見出しの行の探し方は lib/chizu.js の道具だけ★＝2つ目を作らない
 *   ・★見出しの行と その上（表の題）は 隠さない★（何の表か 分からなくなる）
 *
 * 【利用】ブラウザ window.Kirikae / Node require('./kirikae.js')
 */
(function (root) {
  'use strict';

  var どこから = (typeof require === 'function' && typeof module === 'object');
  var CH = どこから ? require('./chizu.js') : root.Chizu;
  var KI = どこから ? require('./kikan.js') : root.Kikan;
  var RC = どこから ? require('./recipe.js') : root.Recipe;

  /* ★決まりは 1か所★（数を 画面に散らさない） */
  var 決まり = { 日が何日以上: 15 };

  function 列の字(c) {
    var s = '';
    c = Number(c);
    while (c >= 0) { s = String.fromCharCode(65 + (c % 26)) + s; c = Math.floor(c / 26) - 1; }
    return s;
  }

  function 端を測る(data) {
    var 最大行 = -1, 最大列 = -1;
    for (var k in data) {
      if (!Object.prototype.hasOwnProperty.call(data, k)) continue;
      var p = k.split(',');
      if (Number(p[0]) > 最大行) 最大行 = Number(p[0]);
      if (Number(p[1]) > 最大列) 最大列 = Number(p[1]);
    }
    return { 最大行: 最大行, 最大列: 最大列 };
  }

  /** ★この表は 切り替えられるか★（人が横に並び 日付の列が在る表だけ）
   *  ★出来ていない物のボタンを見せない★ので、当てはまらない表では 画面に出さない。 */
  function 見る(sheet) {
    var data = (sheet && sheet.data) || {};
    var 端 = 端を測る(data);
    if (端.最大行 < 1 || 端.最大列 < 1) return { つかえる: false, なぜ: '表が 小さすぎます' };

    var み = (CH && CH.見出しの行を探す) ? CH.見出しの行を探す(data, 端.最大列, 5) : { 行: 0, 数: 0 };
    var 見出しの行 = (み.行 >= 0 && み.数 > 0) ? み.行 : 0;

    var 日付の列 = (RC && RC.日付の列を探す)
      ? RC.日付の列を探す(data, 見出しの行, 端.最大行, 端.最大列)
      : { 列: -1, 数: 0 };
    if (日付の列.列 < 0 || !日付の列.数) return { つかえる: false, なぜ: '日付の列が ありません' };

    /* ★人＝見出しの行に 言葉が書いてある列（日付の列は 除く）★ */
    var 人たち = [];
    for (var c = 0; c <= 端.最大列; c++) {
      if (c === 日付の列.列) continue;
      var cell = data[見出しの行 + ',' + c];
      if (!(CH && CH.言葉らしいか && CH.言葉らしいか(cell))) continue;
      人たち.push({ 名: String(cell.v).trim(), 列: c, 字: 列の字(c) });
    }
    if (!人たち.length) return { つかえる: false, なぜ: '人の列が ありません' };

    /* ★どの月が 在るか★（在る月だけ 出す＝空振りの月を 選ばせない） */
    var 月たち = {}, 日の数 = 0, 日にち = {};
    for (var r = 見出しの行 + 1; r <= 端.最大行; r++) {
      var dc = data[r + ',' + 日付の列.列];
      /* ★日付らしいかの見分けは lib/recipe.js の道具だけ★＝2つ作らない
         （小さい数・金額を 日付にしない。実測 2026-08-28） */
      var なか = dc && RC && RC.セルの値 ? RC.セルの値(dc) : null;
      var ymd = (なか !== null && RC.日付らしいか(なか)) ? KI.日付に直す(なか) : null;
      if (!ymd) continue;
      日の数++;
      日にち[ymd] = true;
      月たち[ymd.slice(0, 7)] = true;
    }
    var 月 = Object.keys(月たち).sort();
    /* ★「月で切り替える」に 意味が在る表だけ★（実測 2026-08-28・司さんの本）
         給料表 365日／計算 365日／売上表 31日／距離 31日 … ★日ごとの台帳★
         給料1〜8 は ★別々の日が 1〜2日★（1か月ぶんの明細＝日ごとの台帳ではない）
       ⇒ ★別々の日が 15日（半月）に満たない表では 帯を出さない★
         （出すと「1月分／合計／白石　正人　殿」が ★人★として 並ぶ＝実際に そう出た） */
    var 別々の日 = Object.keys(日にち).length;
    if (別々の日 < 決まり.日が何日以上) {
      return { つかえる: false, なぜ: '日ごとの表では ありません（別々の日が ' + 別々の日 + '日）' };
    }
    return {
      つかえる: 日の数 > 0,
      なぜ: 日の数 > 0 ? '' : '日付が 1つも ありません',
      別々の日: 別々の日,
      見出しの行: 見出しの行,
      日付の列: 日付の列.列,
      人たち: 人たち,
      月たち: 月,
      日の数: 日の数,
      最大行: 端.最大行,
      最大列: 端.最大列,
    };
  }

  /** ★見る所を決める★（隠す行・隠す列を 返すだけ。1セルも 書き換えない）
   * @param {Object} 姿  見る() の返り
   * @param {{人:string, 月:string, 始まりの日:number}} えらび  ''／null は「全員」「全期間」
   */
  function 見る所を決める(sheet, 姿, えらび) {
    えらび = えらび || {};
    var data = (sheet && sheet.data) || {};
    var 隠す行 = {}, 隠す列 = {};
    var 期間 = null;

    if (えらび.月) {
      期間 = KI.期間を決める(えらび.月, えらび.始まりの日 === undefined || えらび.始まりの日 === null ? 1 : えらび.始まりの日);
      if (!期間) return { なぜ: 'いつの分かが 読めません' };
    }

    /* ★人★＝選んだ人 以外の「人の列」を 隠す（日付の列と 人でない列は 触らない） */
    var 人の名 = String(えらび.人 || '');
    if (人の名) {
      var 当たり = 姿.人たち.filter(function (x) { return x.名 === 人の名; });
      if (!当たり.length) return { なぜ: '「' + 人の名 + '」の列が 見つかりません' };
      if (当たり.length > 1) {
        return { なぜ: '「' + 人の名 + '」が ' + 当たり.length + '列 あります（どちらの分か 決められません）' };
      }
      for (var i = 0; i < 姿.人たち.length; i++) {
        if (姿.人たち[i].名 !== 人の名) 隠す列[姿.人たち[i].列] = true;
      }
    }

    /* ★月★＝期間の外の行を 隠す（★見出しの行と その上は 隠さない★）
       ★2026-08-28 実物の絵を見て 直した★
         前は「日付でない行（合計の行など）は そのまま出す」にしていたが、
         実物の給料表は ★途中に 表の題・見出し・合計が 何度も 入る★ ので、
         2/21〜3/20 を選んでも ★別の月の合計や 空行が 混ざって出た★（絵で見える）。
       ⇒ ★Excelのフィルタと 同じ★＝★見出しより下は 当たらない行を 全部 隠す★。
         （見出しの行と その上＝表の題 は 隠さない＝何の表か 分かるように） */
    var 見える行 = 0, 日付の行 = 0;
    for (var r = 姿.見出しの行 + 1; r <= 姿.最大行; r++) {
      var dc = data[r + ',' + 姿.日付の列];
      var ymd = dc ? KI.日付に直す(RC.セルの値(dc)) : null;
      if (ymd) 日付の行++;
      if (!期間) continue;                       /* 月を選んでいない時は 1行も 隠さない */
      if (!ymd || !KI.期間の中か(ymd, 期間)) { 隠す行[r] = true; continue; }
      見える行++;
    }
    if (期間 && !見える行) {
      return { なぜ: 期間.言い方 + 'に 当たる日が 1日も ありません' };
    }

    return {
      隠す行: 隠す行,
      隠す列: 隠す列,
      見える行: 見える行,
      日付の行: 日付の行,
      期間: 期間,
      人: 人の名,
      /* ★今 何を見ているかを 1行★（客に出す言葉は ここ1か所で作る） */
      /* ★「人」と決めつけない★（2026-08-28 指示役）
         ＝実データでは 売上表・距離の見出しが 現金／請求書／PayPay＝人ではない。
           ★機械に「人かどうか」を当てさせない＝当て間違えると 客に嘘を見せる★ */
      いま: (人の名 || '全部') + '／' + (期間 ? 期間.言い方 : '全期間') + '／' + 見える行 + '行',
    };
  }

  /** ★全員・全期間に 戻す★（隠していた物を 空にするだけ） */
  function 戻す() {
    return { 隠す行: {}, 隠す列: {}, いま: '全部／全期間' };
  }

  var api = {
    見る: 見る,
    見る所を決める: 見る所を決める,
    戻す: 戻す,
    決まり: 決まり,
    列の字: 列の字,
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.Kirikae = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
