  /** 「U+00A9」「00A9」「169」 などから 字を 作る
   *  ★組み合わせ文字（U+FFFF より上）も 1文字として 返す★
   *  読めなければ null（★でたらめな 字を 入れない★） */
  function コードから字(入力) {
    var s = String(入力 === null || 入力 === undefined ? '' : 入力).trim();
    if (!s) return null;
    var n = null;
    var m = s.match(/^(?:U\+|u\+|0x|0X)?([0-9A-Fa-f]{1,6})$/);
    if (m && /[A-Fa-f]/.test(m[1])) n = parseInt(m[1], 16);
    else if (/^(?:U\+|u\+|0x|0X)/.test(s) && m) n = parseInt(m[1], 16);
    else if (/^\d+$/.test(s)) n = parseInt(s, 10);
    else if (m) n = parseInt(m[1], 16);
    if (n === null || isNaN(n)) return null;
    if (n < 0 || n > 0x10FFFF) return null;
    if (n >= 0xD800 && n <= 0xDFFF) return null;      /* ★片割れは 字に ならない★ */
    try { return String.fromCodePoint(n); } catch (e) { return null; }
  }

  /** 字 → 「U+XXXX」（見せる用） */
  function 字からコード(字) {
    if (!字) return '';
    var n = String(字).codePointAt(0);
    var h = n.toString(16).toUpperCase();
    while (h.length < 4) h = '0' + h;
    return 'U+' + h;
  }

  return { 記号: 記号, 特殊文字: 特殊文字, コードから字: コードから字, 字からコード: 字からコード };
