/* vba.js — ★マクロ（VBA）の中身を 読む★（純関数・0円・AIを1回も呼ばない）
 * =============================================================================
 * ★何のために（司さん 2026-08-28）★
 *   「Excelでマクロ組んだ人が会社を辞めて 触り方や使い方が分からない人が多いから
 *     ★おれはそれも解決したい★」
 *   ⇒ ★「マクロが入っています」で終わらせない★。★何をしているかを 日本語で言う★。
 *
 * ★決まり★
 *   ・★VBAは 動かさない・触らない★（読むだけ。1バイトも 書き換えない）
 *   ・★AIは 使わない★＝取り出しも 分類も 機械がやる（AIには 後で 要約だけ渡す）
 *   ・★「読めた」と「正しく読めた」は 別★
 *       読めた   … 解凍できた
 *       正しく読めた … ★取り出した物を もう一度 圧縮して 元のバイトと 一致した★
 *     一致しない時は ★往復（解凍→圧縮→解凍）で 中身が 変わっていないか★ を見て
 *     「中身は同じ・詰め方が違う」と ★正直に★ 出す。★黙って「読めた」と言わない★
 *   ・★読めない時は 未測定★（0件・異常なしにしない）
 *
 * ★中身の形（Microsoft の公開仕様 MS-OVBA）★
 *   xl/vbaProject.bin は ★CFB（Excelの .xls と同じ入れ物）★。
 *   その中の `VBA/dir` に ★どのモジュールが どこに在るか★ が書いてある。
 *   どちらも ★MS-OVBA の圧縮★（LZ77の変種）で 縮めてある。
 *   ★JavaScriptの既製品は 見つからなかったので うちで書く★（仕様は公開されている）。
 *
 * 【利用】ブラウザ window.Vba / Node require('./vba.js')
 */
(function (root) {
  'use strict';

  /* ══ ①MS-OVBA の 解凍（2.4.1.3.1）★仕様どおり★ ══════════════ */
  /** @param {Uint8Array} 中身 圧縮された かたまり（先頭は 目印 0x01）
   *  @returns {{ok:boolean, 出:Uint8Array, なぜ:string}} */
  function 解凍(中身) {
    if (!中身 || !中身.length) return { ok: false, 出: new Uint8Array(0), なぜ: '中身が ありません' };
    if (中身[0] !== 0x01) return { ok: false, 出: new Uint8Array(0), なぜ: '目印(0x01)が ありません' };
    var 出 = [];
    var i = 1;
    while (i < 中身.length) {
      if (i + 1 >= 中身.length) break;
      var 頭 = 中身[i] | (中身[i + 1] << 8);
      i += 2;
      var 大きさ = (頭 & 0x0FFF) + 3;              /* かたまりの バイト数（頭の2バイトを含む） */
      var 縮めてある = (頭 & 0x8000) !== 0;
      var 目印 = (頭 >> 12) & 0x07;
      if (目印 !== 0x03) return { ok: false, 出: new Uint8Array(出), なぜ: 'かたまりの目印が 違います' };
      var 終わり = i + 大きさ - 2;
      if (終わり > 中身.length) 終わり = 中身.length;
      if (!縮めてある) {                            /* そのまま 4096バイト */
        for (; i < 終わり; i++) 出.push(中身[i]);
        continue;
      }
      var かたまりの頭 = 出.length;
      while (i < 終わり) {
        var 旗 = 中身[i++];
        for (var b = 0; b < 8 && i < 終わり; b++) {
          if (!((旗 >> b) & 1)) { 出.push(中身[i++]); continue; }   /* そのままの1バイト */
          if (i + 1 >= 終わり) break;              /* 札は 2バイト要る */
          var 札 = 中身[i] | (中身[i + 1] << 8);
          i += 2;
          var 差 = 出.length - かたまりの頭;
          var けた = 何けた(差);
          var 長さの面 = 0xFFFF >> けた;
          var 長さ = (札 & 長さの面) + 3;
          var 前へ = ((札 & ~長さの面 & 0xFFFF) >> (16 - けた)) + 1;
          var 元 = 出.length - 前へ;
          if (元 < 0) return { ok: false, 出: new Uint8Array(出), なぜ: '指す先が 前に 出ました' };
          for (var k = 0; k < 長さ; k++) 出.push(出[元 + k]);      /* ★重なってよい★ */
        }
      }
    }
    return { ok: true, 出: new Uint8Array(出), なぜ: '' };
  }

  /** 何けた使うか（MS-OVBA 2.4.1.3.19.1 CopyToken の けた数） */
  function 何けた(差) {
    var けた = 4;
    while ((1 << けた) < 差) けた++;
    if (けた < 4) けた = 4;
    if (けた > 12) けた = 12;
    return けた;
  }

  /* ══ ②MS-OVBA の 圧縮（2.4.1.3.6）★「正しく読めた」を 確かめるため★ ══ */
  /** @param {Uint8Array} 元 @returns {Uint8Array} */
  function 圧縮(元) {
    var 出 = [0x01];
    var p = 0;
    while (p < 元.length) {
      var かたまりの頭 = p;
      var 終わり = Math.min(p + 4096, 元.length);
      var 札たち = [];                                   /* このかたまりの 中身（バイトの並び） */
      var q = p;
      while (q < 終わり) {
        var 旗 = 0, 束 = [];
        for (var b = 0; b < 8 && q < 終わり; b++) {
          var 差 = q - かたまりの頭;
          var けた = 何けた(差);
          var 長さの面 = 0xFFFF >> けた;
          var いちばん長い = 長さの面 + 3;
          var いちばん前 = (1 << けた);
          var よい = { 長さ: 0, 前へ: 0 };
          var 始め = Math.max(かたまりの頭, q - いちばん前);
          for (var s = 始め; s < q; s++) {                /* ★素直に 一番長い一致を 探す★ */
            var n = 0;
            while (n < いちばん長い && q + n < 終わり && 元[s + n] === 元[q + n]) n++;
            if (n > よい.長さ) { よい.長さ = n; よい.前へ = q - s; }
          }
          if (よい.長さ >= 3) {
            var 札 = ((よい.前へ - 1) << (16 - けた)) | (よい.長さ - 3);
            束.push(札 & 0xFF, (札 >> 8) & 0xFF);
            旗 |= (1 << b);
            q += よい.長さ;
          } else {
            束.push(元[q]);
            q++;
          }
        }
        札たち.push(旗);
        for (var t = 0; t < 束.length; t++) 札たち.push(束[t]);
      }
      var 縮んだ = 札たち.length < (終わり - かたまりの頭);
      var 中 = 縮んだ ? 札たち : Array.prototype.slice.call(元.subarray(かたまりの頭, 終わり));
      /* ★かたまりの大きさ＝頭2バイト＋中身★／書くのは その数−3（仕様 2.4.1.1.5）
         ＝中身の長さ−1。ここを 中身の長さ にすると ★1バイトずつ ずれて 12000バイトで 壊れた★ */
      var 頭 = (((中.length + 2) - 3) & 0x0FFF) | 0x3000 | (縮んだ ? 0x8000 : 0);
      出.push(頭 & 0xFF, (頭 >> 8) & 0xFF);
      for (var u = 0; u < 中.length; u++) 出.push(中[u]);
      p = 終わり;
    }
    return new Uint8Array(出);
  }

  /* ══ ③dir を 読む（2.3.4.2）＝どのモジュールが どこに在るか ══ */
  var 記録 = {
    モジュール名: 0x0019,
    流れの名: 0x001A,
    始まり: 0x0031,      /* TextOffset＝そのモジュールの 圧縮が 始まる所 */
    種類手続き: 0x0021,
    種類クラス: 0x0022,
    文字の種類: 0x0003,
  };

  function 字にする(b) {
    var s = '';
    for (var i = 0; i < b.length; i++) s += String.fromCharCode(b[i]);
    return s;
  }
  /** ★Unicode（UTF-16LE）の名前を 読む★＝日本語のモジュール名でも 化けない */
  function 字にする16(b) {
    var s = '';
    for (var i = 0; i + 1 < b.length; i += 2) s += String.fromCharCode(b[i] | (b[i + 1] << 8));
    return s;
  }

  function dirを読む(dir) {
    var 出 = [], 今 = null, 字の種類 = 0, 言う本数 = -1, 行き止まり = '';
    var i = 0;
    while (i + 6 <= dir.length) {
      var id = dir[i] | (dir[i + 1] << 8);
      var 大きさ = dir[i + 2] | (dir[i + 3] << 8) | (dir[i + 4] << 16) | (dir[i + 5] << 24);
      /* ★ここだけ 大きさが 嘘★＝PROJECTVERSION(0x0009) は
         「4」と書いてあるのに 中身は 6バイト（大きい方4＋小さい方2）。
         そのまま 4 で進むと ★2バイト 手前に 着地して 目次が 総崩れ★になる。
         実物5本 ぜんぶ ここで 行き止まりになり、★マクロ0本★と出ていた（2026-08-28 実測）。 */
      if (id === 0x0009) 大きさ = 6;
      i += 6;
      if (大きさ < 0 || i + 大きさ > dir.length) {
        行き止まり = '目次の 途中で 読めなくなりました';
        break;
      }
      var 中 = dir.subarray(i, i + 大きさ);
      if (id === 記録.文字の種類 && 大きさ >= 2) {
        字の種類 = 中[0] | (中[1] << 8);          /* PROJECTCODEPAGE（932＝日本語） */
      } else if (id === 0x000F && 大きさ >= 2) {
        言う本数 = 中[0] | (中[1] << 8);          /* PROJECTMODULES＝目次が 言う 本数 */
      } else if (id === 記録.モジュール名) {
        if (今) 出.push(今);
        今 = { 名: 字にする(中), 流れ: '', 始まり: 0, 種類: '' };
      } else if (id === 0x0047 && 今 && !今.名) {
        今.名 = 字にする16(中);
      } else if (id === 記録.流れの名 && 今) {
        今.流れ = 字にする(中);
      } else if (id === 0x0032 && 今 && !今.流れ) {
        今.流れ = 字にする16(中);
      } else if (id === 記録.始まり && 今) {
        今.始まり = 中[0] | (中[1] << 8) | (中[2] << 16) | (中[3] << 24);
      } else if (id === 記録.種類手続き && 今) {
        今.種類 = '手続き';
      } else if (id === 記録.種類クラス && 今) {
        今.種類 = 'クラス';
      }
      i += 大きさ;
    }
    if (今) 出.push(今);
    return { 一覧: 出, 字の種類: 字の種類, 言う本数: 言う本数, 行き止まり: 行き止まり };
  }

  /* ══ ③-b 中身の 字づかい ══════════════════════════════════
     ★VBAの中身は Unicode では 置いていない★＝その国の文字の種類（日本語は 932）で
     置いてある。1バイトずつ 読むと 日本語が 化ける（実測 2026-08-28）。 */
  var 字の種類の名 = {
    932: 'shift_jis', 936: 'gbk', 949: 'euc-kr', 950: 'big5',
    1200: 'utf-16le', 1250: 'windows-1250', 1251: 'windows-1251',
    1252: 'windows-1252', 1253: 'windows-1253', 1254: 'windows-1254',
    65001: 'utf-8',
  };
  var 読み手の控え = {};
  /** 中身のバイトを 字に直す。読めない字づかいなら null（＝未測定にする） */
  function 中身を字にする(b, cp) {
    var 名 = 字の種類の名[cp] || '';
    if (!名) return { 文: 字にする(b), 字づかい: (cp ? String(cp) : '不明'), 確か: false };
    if (!(名 in 読み手の控え)) {
      try { 読み手の控え[名] = new TextDecoder(名, { fatal: false }); }
      catch (e) { 読み手の控え[名] = null; }
    }
    var d = 読み手の控え[名];
    if (!d) return { 文: 字にする(b), 字づかい: 名, 確か: false };
    return { 文: d.decode(b), 字づかい: 名, 確か: true };
  }

  /** ★1バイトずつ 同じか★＝長さだけ見て 同じと言わない
      （長さが 同じで 中身が 違う物は 実際に ある） */
  function 同じバイト列(a, b) {
    if (!a || !b || a.length !== b.length) return false;
    for (var i = 0; i < a.length; i++) if (a[i] !== b[i]) return false;
    return true;
  }

  /* ══ ④まとめて 読む ══════════════════════════════════════ */
  /**
   * @param {Uint8Array} bin  xl/vbaProject.bin（★読むだけ★）
   * @param {Object} CFB      XLSX.CFB（入れ物を開く道具）
   * @returns {{ok, モジュール:[{名,種類,行数,中身,確か,なぜ}], なぜ, 確かめ:{一致,往復,全部}}}
   */
  function 読む(bin, CFB) {
    if (!bin || !bin.length) return { ok: false, モジュール: [], なぜ: 'マクロが ありません' };
    if (!CFB || !CFB.read) return { ok: false, モジュール: [], なぜ: '入れ物を開く道具が ありません' };
    var 箱;
    try { 箱 = CFB.read(bin, { type: 'array' }); }
    catch (e) { return { ok: false, モジュール: [], なぜ: '入れ物が 読めませんでした' }; }

    var 流れ = {};
    for (var i = 0; i < 箱.FileIndex.length; i++) {
      var 名 = String(箱.FullPaths[i] || '').replace(/^[^/]*\//, '');   /* 先頭の入れ物名を落とす */
      if (箱.FileIndex[i].type === 2) 流れ[名] = 箱.FileIndex[i].content;
    }
    var dirの元 = 流れ['VBA/dir'] || 流れ['VBA/DIR'] || null;
    if (!dirの元) return { ok: false, モジュール: [], なぜ: 'dir（目次）が ありません' };

    var d = 解凍(new Uint8Array(dirの元));
    if (!d.ok) return { ok: false, モジュール: [], なぜ: '目次が 解凍できませんでした（' + d.なぜ + '）' };
    var 目次 = dirを読む(d.出);
    var 一覧 = 目次.一覧;
    var 字づかい = 目次.字の種類;
    /* ★0本を 黙って返さない★＝「見つからなかった」は 結果ではなく ★読めていない★
       （実物5本で ok:true・0本 を 返していた。2026-08-28） */
    if (!一覧.length) {
      return { ok: false, モジュール: [], なぜ: 目次.行き止まり || '目次に マクロが 1本も 書かれていません' };
    }

    var 出 = [], 確か = 0, 往復 = 0, 詰め方も同じ = 0, 名前一致 = 0;
    for (var m = 0; m < 一覧.length; m++) {
      var x = 一覧[m];
      var 名前 = x.流れ || x.名;
      var st = 流れ['VBA/' + 名前] || 流れ[名前] || null;
      if (!st) { 出.push({ 名: x.名, 種類: x.種類, 行数: 0, 中身: '', 確か: false, なぜ: '中身が 見つかりません' }); continue; }
      var 生 = new Uint8Array(st).subarray(x.始まり);
      var r = 解凍(生);
      if (!r.ok) { 出.push({ 名: x.名, 種類: x.種類, 行数: 0, 中身: '', 確か: false, なぜ: '解凍できません（' + r.なぜ + '）' }); continue; }
      var よ = 中身を字にする(r.出, 字づかい);
      var 文 = よ.文;
      /* ══ ★「読めた」と「正しく読めた」を 分ける★（証拠は 3つ・別々に 数える） ══
         ①詰め方も同じ … もう一度 圧縮して ★元のバイトと 1バイトずつ 一致★（いちばん強い）
           ★実物では ここは 0本になる★＝Excelの詰め方と うちの詰め方が 違うだけで、
           中身が 違うわけではない（司さんの実物 59本 中 0本。2026-08-28 実測）。
           ⇒ ★これ1つだけを「正しく読めた」にすると、実物では 一生 0本になる★
         ②往復 … 圧縮し直して 解凍すると ★同じバイトに 戻る★
         ③名前が合う … ★目次に書いてある名前★と ★中身の1行目（Attribute VB_Name）★が 一致
           ＝★別々の所から来た 2つが 合う★。読み違えていたら 合わない（実物 59/59 一致）。
         ★正しく読めた＝②と③が 両方 通り、字づかいも 読めた時だけ★ */
      var また = 圧縮(r.出);
      var 同じバイト = 同じバイト列(また, 生);
      var 往復同じ = 同じバイト;
      if (!同じバイト) {
        var r2 = 解凍(また);
        往復同じ = !!(r2.ok && 同じバイト列(r2.出, r.出));
      }
      var 頭 = /^Attribute VB_Name = "(.*)"/.exec(String(文).split(/\r\n|\r|\n/)[0] || '');
      var 名前が合う = !!(頭 && 頭[1] === x.名);
      var 正しい = !!(往復同じ && 名前が合う && よ.確か);
      if (同じバイト) 詰め方も同じ++;
      if (名前が合う) 名前一致++;
      if (往復同じ) 往復++;
      if (正しい) 確か++;
      出.push({
        名: x.名, 種類: x.種類,
        行数: 文 ? 文.split(/\r\n|\r|\n/).length : 0,
        中身: 文,
        字づかい: よ.字づかい,
        確か: 正しい,
        詰め方も同じ: 同じバイト,
        名前が合う: 名前が合う,
        なぜ: !よ.確か ? '字づかい（' + よ.字づかい + '）が 読めません（未測定）'
          : (!往復同じ ? '往復で 中身が 変わりました（未測定）'
            : (!名前が合う ? '目次の名前と 中身の1行目が 合いません（未測定）'
              : (同じバイト ? '' : '中身は同じ・詰め方が違う'))),
      });
    }
    /* ★目次が言う本数と 取れた本数が 違えば そう言う★（多い方に 黙って 合わせない） */
    var 食い違い = (目次.言う本数 >= 0 && 目次.言う本数 !== 出.length)
      ? ('目次は ' + 目次.言う本数 + '本と 言っていますが ' + 出.length + '本しか 取れませんでした') : '';
    return {
      ok: true, モジュール: 出, なぜ: 食い違い || 目次.行き止まり,
      確かめ: {
        一致: 確か,                 /* ★正しく読めた＝往復＋名前＋字づかい★ */
        詰め方も同じ: 詰め方も同じ,  /* 元のバイトと 1バイトずつ 同じ（実物では 0になる） */
        名前一致: 名前一致,
        往復: 往復,
        全部: 出.length,
        目次: 目次.言う本数,
      },
    };
  }

  var api = {
    解凍: 解凍, 圧縮: 圧縮, dirを読む: dirを読む, 読む: 読む, 何けた: 何けた,
    同じバイト列: 同じバイト列,
    中身を字にする: 中身を字にする,
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.Vba = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
