  'use strict';

  var 数字 = ['', 'หนึ่ง', 'สอง', 'สาม', 'สี่', 'ห้า', 'หก', 'เจ็ด', 'แปด', 'เก้า'];
  var 位 = ['', 'สิบ', 'ร้อย', 'พัน', 'หมื่น', 'แสน'];
  var ゼロ = 'ศูนย์', ラーン = 'ล้าน', バーツ = 'บาท', サタン = 'สตางค์';
  var チュアン = 'ถ้วน', エット = 'เอ็ด', イー = 'ยี่', シップ = 'สิบ', ロブ = 'ลบ';

  /** ★1〜999,999 を 字に する★
   *  @param n      その かたまり（0 なら 空）
   *  @param 上が在る 上の 位（別の かたまり）に 何か 在るか＝一の位の 1 を เอ็ด に するか
   */
  function 六桁を字に(n, 上が在る) {
    var s = String(n), 出 = '';
    for (var i = 0; i < s.length; i++) {
      var d = +s[i];
      var 桁 = s.length - 1 - i;              /* 0=一の位 */
      if (!d) continue;
      if (桁 === 1) {                          /* 十の位 */
        出 += (d === 1) ? シップ : (d === 2 ? イー + シップ : 数字[d] + シップ);
      } else if (桁 === 0) {                   /* 一の位 */
        出 += (d === 1 && (出 !== '' || 上が在る)) ? エット : 数字[d];
      } else {
        出 += 数字[d] + 位[桁];
      }
    }
    return 出;
  }

  /** ★整数を 字に する★（100万ごとに ล้าน を 重ねる） */
  function 整数を字に(n, 上が在る) {
    if (n === 0) return '';
    var 上 = Math.floor(n / 1000000), 下 = n % 1000000;
    if (上 > 0) {
      return 整数を字に(上, 上が在る) + ラーン + 六桁を字に(下, true);
    }
    return 六桁を字に(下, 上が在る);
  }

  /** ★小数2桁に 丸める★＝★字（10進）に 直してから 丸める★
   *  ★数の まま 100倍して 丸めると ずれる★（2.675 は 機械の 中では 2.67499…）
   *  返り値 { 整数: 数, サタン: 0〜99, 負: true/false }
   */
  function 二桁に丸める(x) {
    var 負 = x < 0;
    var v = Math.abs(x);
    if (!isFinite(v)) return null;
    /* ★15桁まで の 字に する★＝Excel が 数を 見せる 時と 同じ 桁数 */
    var s = v.toPrecision(15);
    if (s.indexOf('e') >= 0 || s.indexOf('E') >= 0) s = 大きい数を字に(v);
    var 点 = s.indexOf('.');
    var 整 = (点 < 0) ? s : s.slice(0, 点);
    var 小 = (点 < 0) ? '' : s.slice(点 + 1);
    while (小.length < 3) 小 += '0';
    var サ = +小.slice(0, 2);
    if (+小[2] >= 5) サ += 1;                  /* ★半分は 上へ★（実測 0.005→1・0.045→5） */
    var 円 = 整.replace(/^0+(?=\d)/, '');
    if (サ >= 100) { サ -= 100; 円 = 足す1(円); }
    return { 整数: 円, サタン: サ, 負: 負 };
  }

  /** ★字のままの 整数に 1 を 足す★（大きい 数でも 桁が 落ちない） */
  function 足す1(s) {
    var a = s.split(''), i = a.length - 1;
    while (i >= 0) {
      if (a[i] === '9') { a[i] = '0'; i--; continue; }
      a[i] = String(+a[i] + 1); return a.join('');
    }
    return '1' + a.join('');
  }

  /** ★指数の 形（1e+21 など）を ふつうの 字に する★
   *  ★toFixed(0) は 1e21 以上で また 指数に なる★（2026-09-04 実測＝1e21 で 外した）
   *  ⇒★字を 自分で 組み立てる★ */
  function 大きい数を字に(v) {
    var s = v.toPrecision(15);
    var m = /^(-?)(\d)(?:\.(\d*))?e\+(\d+)$/i.exec(s);
    if (!m) return String(s);
    var 符 = m[1], 頭 = m[2], 続 = m[3] || '', 乗 = +m[4];
    var 桁 = 頭 + 続;
    while (桁.length < 乗 + 1) 桁 += '0';
    return 符 + 桁.slice(0, 乗 + 1) + (桁.length > 乗 + 1 ? ('.' + 桁.slice(乗 + 1)) : '');
  }

  /** ★字のままの 整数を 字に する★（Number に 戻さない＝大きい 数で 桁が 落ちない） */
