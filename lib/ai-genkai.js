/* ai-genkai.js — ★AIを 何回 叩けるか／1回に どれだけ 送れるか＝★数は ここ 1か所★★
 *
 *  ★なぜ 出来たか（2026-09-05 実測）★
 *    同じ「回数」の 決まりが ★2か所★に 在った。
 *      画面 … `lib/horu.js` 掘れる回数を決める(sheets) ⇒ ★実物ブックで 13★
 *             `book.html` の ループは ★掘れる + 2 ＝ 15回 AIを 叩く★
 *      サーバ … `api/claude.js` 事故止め.分の回数 ＝ ★10★
 *    ⇒★15回 叩く つもりで 10回で 止まる（5回 足りない）★
 *    ⇒ しかも 止まると `book.html` は `break` して
 *      ★それまでの 掘りを 全部 捨てて「使いすぎ」だけ 出す★
 *    ⇒★「大きいブックほど うちが 強い」が「大きいブックほど 必ず 失敗する」に なっていた★
 *
 *  ★同じ家の 事故★＝`api/claude.js` の 事故止めには
 *    「★数字は ここ1か所だけ★（散らすと 直す時に 必ず 片方が残る）」と 書いてあった。
 *    ★書いてあったのに 掘る数だけ 外に 在った★。だから ここへ 集める。
 *
 *  ★使い方★
 *    サーバ  … const 限界 = require('../lib/ai-genkai.js');
 *    画面    … <script src="lib/ai-genkai.js"> ⇒ window.AiGenkai
 *  ★見張り★ tests/ai-genkai.test.mjs（★掘る数 > 叩ける数 なら 赤★）
 */
(function (root) {
  'use strict';

  var 限界 = {
    /* ★1分に 何回 AIを 叩けるか（人ごと）★
       司さん承認 2026-08-22／数字は 指示役 2026-08-25。★お金の 上限＝これが 正★ */
    分の回数: 10,

    /* ★1回に 送れる 字数★（前置き＋会話＋材料を 足した 後） */
    一度の字数: 20000,

    /* ★1回の やりとりで AIを 叩いてよい 回数★
       ★分の回数より 必ず 小さく する★＝1人が 1分に 1回しか 聞かない とは 限らない。
       ★2 は 掘り直し・付け直しの 余裕★（book.html が +2 している分を ここに 含める）。 */
    一問で叩ける: 8,
  };

  /** ★掘ってよい 回数★＝ブックの 大きさから 出した 数を ★叩ける数で 頭打ち★にする。
   *  ★掘りきれない 時は 掘らずに「ここまで」と 言う★（黙って 止まらない）。 */
  function 掘ってよい回数(ブックから出した数) {
    var 上 = 限界.一問で叩ける - 2;              /* +2 の 余裕を 引く */
    var n = Math.max(1, Math.min(Number(ブックから出した数) || 1, 上));
    return n;
  }

  /** ★このブックを 掘りきれるか★（＝客に 正直に 言う為）
   *  ★渡すのは「ブックの 大きさから 出した 数（頭打ち前）」★
   *  ★2026-09-05 に 1回 間違えた★＝頭打ち後の 6 を 渡して「掘りきれる」と 出た。
   *    ⇒ 頭打ち後の 数は ★必ず 上限以下★なので ★いつも true★＝★見張りが 死ぬ★。
   *    ⇒ 引数の 意味を 名前に 書く。 */
  function 掘りきれるか(ブックから出した数_頭打ち前) {
    var 要る = Number(ブックから出した数_頭打ち前) || 0;
    return 要る > 0 && 要る <= 限界.一問で叩ける - 2;
  }

  /** ★ブックの 大きさから「頭打ち前に 何回 要るか」を 出す★（掘りきれるか に 渡す為） */
  function 要る回数(全セル数, 一度のセル) {
    var n = Math.max(1, Number(一度のセル) || 2000);
    return Math.ceil((Number(全セル数) || 0) / n) + 2;
  }

  var api = { 限界: 限界, 掘ってよい回数: 掘ってよい回数, 掘りきれるか: 掘りきれるか, 要る回数: 要る回数 };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  if (typeof window !== 'undefined') window.AiGenkai = api;
  else if (typeof globalThis !== 'undefined') globalThis.AiGenkai = api;
})(typeof self !== 'undefined' ? self : this);
