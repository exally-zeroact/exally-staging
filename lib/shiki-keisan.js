/* shiki-keisan.js — ★つなぎ（＋−×÷＾＆ 大小 ％）を 実Excel どおりに する★（2026-09-11）
 *
 *  ★★土台を 自分で 作る ④枚目の 前半★★
 *    土台は 5つ … ①字に 切る ②形に する ③頼りの 地図 ④★順番と 計算★ ⑤溢れ
 *    ここは ★1マスの 値どうしを つなぐ 所だけ★＝関数と 四角（A1:A3）は 入って いません。
 *    ★出来て いない 物を 出来た 顔で 混ぜない★ 為に 分けて います。
 *
 *  ★★借り物の 中は 1文字も 読んで いません★★
 *  ★★答えは 全部 実Excel に 打って 測りました★★（2026-09-11・5回に 分けて 130通り）
 *
 *  ★★当て推量なら 外して いた 物（実Excel に 聞いて 初めて 分かった）★★
 *    `=0^0`      → ★#NUM!★（1 では ない）
 *    `=2^3^2`    → ★64★（左から 結ぶ。512 では ない）
 *    `=-2^2`     → ★4★（前に 付く − の 方が ＾より 強い）
 *    `=+"1"`     → ★字の まま★（前に 付く ＋ は 数に しない）
 *    `="(1)"+0`  → ★-1★（丸括弧は マイナス）
 *    `="1,000"+0`→ ★1000★（3桁区切りは 通る）
 *    `="1 000"+0`→ ★#VALUE!★（空白は 通らない）
 *    `=TRUE=1`   → ★FALSE★（真偽と 数は 決して 同じに ならない）
 *    `=""=0`     → ★FALSE★ なのに 空マス `=D1=0` → ★TRUE★（空の 字と 空マスは 別物）
 *    `=NA()+1/0` → ★#N/A★ ／ `=1/0+NA()` → ★#DIV/0!★（★左の 誤りが 勝つ★）
 *    `=(-8)^(1/3)`→★-2★（1÷指が 奇数なら 通る）／`=(-8)^(1/2)`→★#NUM!★
 *
 *  ★値の 形★ { 型:'数'|'字'|'真偽'|'誤'|'空', 値 }
 *    ★空★＝何も 入って いない マス。★空の 字（""）とは 別物です★
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.ShikiKeisan = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  var 数 = function (v) { return { 型: '数', 値: v }; };
  var 字 = function (v) { return { 型: '字', 値: v }; };
  var 真偽 = function (v) { return { 型: '真偽', 値: !!v }; };
  var 誤 = function (v) { return { 型: '誤', 値: v }; };
  var 空 = { 型: '空', 値: '' };

  /* ══ ★★15桁の 決まりは 3つに 分かれて います★★ ══
     ★実Excel は 15桁より 細かい 所を 持ちません★が、
     ★どこで 15桁に するかが 3通り 違います★（実測で 分かった・当て推量では 外す）

       ①★打った 数★は ★切り捨て★（16桁目から 先を 0に する）
           `=1234567890123456&""` → ★1234567890123450★（…460 では ない）
       ②★＋と − と 大小くらべ★は ★消え残りを 0に する★
           `=0.1+0.2-0.3` → ★0★ ／ `=2/3*3=2` → ★TRUE★（下の 消え残りを消す）
       ③★×と ÷と ＾ の 途中は 丸めません★
           丸めると `=1/3*3-1` が -0.000000000000001 に なって しまいます。
           ★「×を 丸めるか どうか」は 150通り 測っても 差が 出ませんでした★
           ⇒★差が 出ない 方を 選んで います（機械の まま）★
       ④★画面に 出す 時★は ★丸める★（`数を字に` の 中だけ）
           `=2/3&""` → ★0.666666666666667★（切り捨てなら …666 に なって しまう）
           ★丸める 所は この 台に 2か所だけ★（`平らに` と `指数の形`）＝丸めの 一覧に 載せて 在る */
  /** ★消え残りを 0に する★（＋と −と 大小くらべ）
   *
   *  ★★実Excel は 引き算で ほとんど 消えた 時、残りを 0に します★★（実測）
   *    `=0.1+0.2-0.3`          → ★0★（機械の 中では 0.0000000000000000555 が 残る）
   *    `=(2/3*3-2)*1E16`       → ★0★
   *    `=2/3*3*1E16-2E16`      → ★0★（残り -2 も 元が 2京なので 消え残り）
   *  ★大小くらべも 同じ 引き算で 見て います★
   *    `=2/3*3=2`     → ★TRUE★（機械の 中では 1.9999999999999998）
   *    `=0.1+0.2=0.3` → ★TRUE★
   *  ⇒★元の 大きさの 15桁目より 下は 無い物として 扱う★ */
  function 消え残りを消す(r, a, b) {
    if (r === 0 || !isFinite(r)) return r;
    var 大 = Math.max(Math.abs(a), Math.abs(b));
    /* ★★境目を 1e-15 に して いました★★（2026-09-16 実測で 直した）
         `=1e15+1-1e15` … 実Excel ★1★ ／ うち ★0★
         ＝残り 1 に 対し 大きい 方の 数が 1.000000000000001e15
           ⇒ 比は ★9.99e-16★で 1e-15 を ★わずかに 下回る★⇒消して いた
       ★境目を 挿む 2本★（この 2本で 挿まれて います）
         ★消す★   `=1-0.9-0.1` … 比 ★2.78e-16★（実Excel 0）
         ★消さない★ `=1e15+1-1e15` … 比 ★9.99e-16★（実Excel 1）
       ⇒★ 5e-16★（≤ 4つ分の ulp＝引き算で 消え合った 時に 残る 大きさ）
       ★この 数は 理屈では なく ★上の 2本が 決めて います★★ */
    if (大 !== 0 && Math.abs(r) < 大 * 5e-16) return 0;
    return r;
  }
  /** ★★消え残りを 消す のは ★式の 一番 最後の 演算★ だけです★★（2026-09-16 実測）
   *    `=0.1+0.2-0.3`        → ★0★          （最後が 引き算）
   *    `=(0.1+0.2-0.3)*1`    → ★5.55e-17★   （最後が 掛け算）
   *    `=(0.1+0.2-0.3)+0`    → ★5.55e-17★   （★括弧で 印が 落ちる★）
   *    `=ABS(0.1+0.2-0.3)`   → ★5.55e-17★   （★関数に 入ると 印が 落ちる★）
   *    `=2/3*3-2=0`          → ★TRUE★       （★くらべる 相手に なる 時は 締める★）
   *    `=(0.1+0.2-0.3)=0`    → ★FALSE★      （括弧で 印が 落ちて いる）
   *  ⇒★前は ★＋と－の その場で★ 消して いた★＝★関数の 中まで 漏れて いた★
   *  ⇒★★消した 後の 数を ★印★ と して 持たせ、使う 側が 取る★★ */
  function 足し引きを締める(v) {
    if (v && v.消えたら !== undefined) return 数(v.消えたら);
    return v;
  }
  /** ★括弧・関数を 通ったら 印を 落とす★ */
  function 印を落とす(v) {
    if (v && v.消えたら !== undefined) return 数(v.値);
    return v;
  }
  function 零を並べる(k) { return k > 0 ? new Array(k + 1).join('0') : ''; }
  /** ★打った 数を 15桁で 切る★（①）＝16桁目から 先を 0に する
   *  ★丸めては いけません★（実測 1234567890123456 → 1234567890123450）
   *
   *  ★★切るのは「打った 字」です。機械の 中の 数では ありません★★
   *    機械の 中では `0.3` は 0.29999999999999998889… `1E-20` は 9.9999…E-21 です。
   *    ★そこを 切ると `0.3` が 0.299999999999999 に なって しまいます★
   *    （2026-09-11 実際に そう して 6本 外しました） */
  function 打った数(字) {
    var t = String(字).trim();
    var m = /^([+-]?)(\d*)(?:\.(\d*))?(?:[eE]([+-]?\d+))?$/.exec(t);
    if (!m) return Number(t);
    var 整 = m[2] || '', 小 = m[3] || '';
    var 並 = 整 + 小;
    var 頭 = 並.search(/[1-9]/);          /* ★先頭の 0 は 桁に 数えない★ */
    if (頭 < 0) return Number(t);
    if (並.length - 頭 <= 15) return Number(t);   /* ★15桁 以内＝そのまま★ */
    var 切 = 並.slice(0, 頭 + 15) + 零を並べる(並.length - 頭 - 15);
    var s = (m[1] === '-' ? '-' : '') + 切.slice(0, 整.length) +
            (小 ? '.' + 切.slice(整.length) : '') + (m[4] ? 'e' + m[4] : '');
    return Number(s);
  }

  /* ══ ★数 → 字★（＆ で つなぐ 時の 形）══ */
  function 縮める(t) {
    if (t.indexOf('.') < 0) return t;
    return t.replace(/0+$/, '').replace(/\.$/, '');
  }
  function 指数の形(n) {
    var t = n.toExponential(14);
    var i = t.indexOf('e');
    var m = 縮める(t.slice(0, i));
    var e = t.slice(i + 1);
    return m + 'E' + e.charAt(0) + e.slice(1).replace(/^0+(?=\d)/, '');
  }
  function 平らに(n) {
    var t = n.toPrecision(15);
    var i = t.search(/[eE]/);
    if (i < 0) return 縮める(t);
    var m = t.slice(0, i), e = Number(t.slice(i + 1));
    var 負 = m.charAt(0) === '-';
    if (負 || m.charAt(0) === '+') m = m.slice(1);
    var 点 = m.indexOf('.');
    var 並 = (点 < 0) ? m : (m.slice(0, 点) + m.slice(点 + 1));
    var 位 = (点 < 0 ? m.length : 点) + e;
    var s;
    if (位 <= 0) s = '0.' + 零を並べる(-位) + 並;
    else if (位 >= 並.length) s = 並 + 零を並べる(位 - 並.length);
    else s = 並.slice(0, 位) + '.' + 並.slice(位);
    return (負 ? '-' : '') + 縮める(s);
  }
  /** ★数を 字に する★（実Excel の「標準」）
   *  ★指数の 形に なる 境目も 測りました★
   *    1e19 → `10000000000000000000`（平ら）／★1e20 → `1E+20`★
   *    1e-18 → `0.000000000000000001`（平ら）／★1e-19 → `1E-19`★ */
  function 数を字に(n) {
    if (n === 0) return '0';                 /* ★-0 も `0`★（実測） */
    if (!isFinite(n)) return '#NUM!';
    var a = Math.abs(n);
    if (a >= 1e20 || a < 1e-18) return 指数の形(n);
    return 平らに(n);
  }

  /* ══ ★字 → 数★（実Excel が 通す 形だけ）══ */
  var 数の形 = /^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/;
  /* ★3桁区切り★＝コンマの 後ろは ★3桁 以上★（実測）
     通る `1,000` `1,0000` `1,000,000` `1234,567` ／ 通らない `1,00,0` `12,34` `,100` `1,` */
  var 区切りの形 = /^[+-]?\d+(,\d{3,})+(\.\d+)?$/;
  /**
   * @param 手 { 字を日付に } … ★日付の 字（"2026/1/1"→46023）は この 台では 読みません★
   *   実Excel は 通しますが、日付の 読み方は 別の 台の 仕事です。
   *   ★渡されなければ 日付の 字は #VALUE! に します★＝★半分 合う 答えを 出さない★
   */
  function 字を数に(s, 手) {
    var 元 = String(s);
    var t = 元.trim();
    if (t === '') return null;                /* ★空の 字は 数に ならない★（実測 #VALUE!） */
    var 負 = false;
    if (t.charAt(0) === '(' && t.charAt(t.length - 1) === ')') { 負 = true; t = t.slice(1, -1).trim(); }
    var 百分 = false;
    if (t.charAt(t.length - 1) === '%') { 百分 = true; t = t.slice(0, -1).trim(); }
    var u = t;
    if (u.indexOf(',') >= 0) {
      if (!区切りの形.test(u)) return 日付に(元, 手);
      u = u.replace(/,/g, '');
    }
    if (!数の形.test(u)) return 日付に(元, 手);
    var n = Number(u);
    if (百分) n = n / 100;
    return 負 ? -n : n;
  }
  function 日付に(元, 手) {
    if (手 && typeof 手.字を日付に === 'function') {
      var d = 手.字を日付に(元);
      if (typeof d === 'number' && isFinite(d)) return d;
    }
    return null;
  }

  /* ══ ★数に する★（＋−×÷＾ の 前に 通す）══ */
  function 数にする(v, 手) {
    if (v.型 === '誤') return v;
    if (v.型 === '数') return v;
    if (v.型 === '空') return 数(0);           /* ★空マスは 0★（実測 `=D1+1` → 1） */
    if (v.型 === '真偽') return 数(v.値 ? 1 : 0);
    var n = 字を数に(v.値, 手);
    if (n === null) return 誤('#VALUE!');
    return 数(n);
  }
  /* ══ ★字に する★（＆ の 前に 通す）══ */
  function 字にする(v) {
    if (v.型 === '誤') return v;
    if (v.型 === '字') return v;
    if (v.型 === '空') return 字('');          /* ★空マス＆"x" → "x"★（実測） */
    if (v.型 === '真偽') return 字(v.値 ? 'TRUE' : 'FALSE');
    return 字(数を字に(v.値));
  }

  /* ══ ★大小くらべ★ ══
     ★並び順は 実測★ 数 ＜ 字 ＜ FALSE ＜ TRUE
       `=1<"a"` → TRUE ／ `="a"<TRUE` → TRUE ／ `=TRUE>1` → TRUE
     ★字は 大文字小文字を 見ません★ `="a"="A"` → TRUE ／ `="Z"<"a"` → FALSE
     ★空マスは 相手の 型に なります★
       `=D1=0` → TRUE ／ `=D1<"a"` → TRUE ／ `=D1<FALSE` → FALSE ／ `=D1<TRUE` → TRUE */
  var 型の順 = { '数': 0, '字': 1, '真偽': 2 };
  function 空を合わせる(a, b) {
    if (a.型 !== '空') return a;
    if (b.型 === '字') return 字('');
    if (b.型 === '真偽') return 真偽(false);
    return 数(0);
  }
  function 並び(a, b) {
    if (a.型 !== b.型) return 型の順[a.型] < 型の順[b.型] ? -1 : 1;
    if (a.型 === '数') {
      var d = 消え残りを消す(a.値 - b.値, a.値, b.値);   /* ★②★ */
      return d < 0 ? -1 : (d > 0 ? 1 : 0);
    }
    if (a.型 === '字') {
      var x = String(a.値).toUpperCase(), y = String(b.値).toUpperCase();
      return x < y ? -1 : (x > y ? 1 : 0);
    }
    var p = a.値 ? 1 : 0, q = b.値 ? 1 : 0;
    return p < q ? -1 : (p > q ? 1 : 0);
  }

  /* ══ ★＾（累乗）★ ══
     ★負の 数を 底に する 時★（実測）
       整数の 指 … 通る `=(-8)^2`→64 `=(-8)^3`→-512
       1÷指が ★奇数★ … 通る `=(-8)^(1/3)`→-2 `=(-32)^(1/5)`→-2 `=(-8)^(-1/3)`→-0.5
       それ以外 … ★#NUM!★ `=(-8)^(1/2)` `=(-8)^(1/4)` `=(-8)^(2/3)` `=(-8)^(3/5)`
     ★0 を 底に する 時★ `=0^0`→#NUM! ／ `=0^-1`→#DIV/0! ／ `=0^0.5`→0 */
  function 累乗(底, 指) {
    if (底 === 0) {
      if (指 === 0) return 誤('#NUM!');
      if (指 < 0) return 誤('#DIV/0!');
      return 数(0);
    }
    if (底 < 0 && 指 !== Math.round(指)) {
      var 逆 = 1 / 指;
      var 丸 = Math.round(逆);
      if (Math.abs(逆 - 丸) > 1e-10 || 丸 % 2 === 0) return 誤('#NUM!');
      var r = Math.pow(-底, 指);
      if (!isFinite(r)) return 誤('#NUM!');
      return 数(-r);
    }
    var v = Math.pow(底, 指);
    if (!isFinite(v)) return 誤('#NUM!');
    return 数(v);
  }

  /* ══ ★つなぎ（2つを 結ぶ）★ ══
     ★誤りは 左が 勝ちます★（実測 `=NA()+1/0`→#N/A ／ `=1/0+NA()`→#DIV/0!） */
  function つなぎ(記, 左, 右, 手) {
    if (左.型 === '誤') return 左;
    if (右.型 === '誤') return 右;

    if (記 === '&') {
      var a = 字にする(左); if (a.型 === '誤') return a;
      var b = 字にする(右); if (b.型 === '誤') return b;
      return 字(a.値 + b.値);
    }

    if (記 === '=' || 記 === '<>' || 記 === '<' || 記 === '>' || 記 === '<=' || 記 === '>=') {
      var p = 空を合わせる(左, 右), q = 空を合わせる(右, 左);
      if (p.型 === '空' && q.型 === '空') { p = 数(0); q = 数(0); }
      /* ★くらべる 相手に なる 時は ★締めてから★★（`=2/3*3-2=0` → TRUE） */
      var c = 並び(足し引きを締める(p), 足し引きを締める(q));
      if (記 === '=') return 真偽(c === 0);
      if (記 === '<>') return 真偽(c !== 0);
      if (記 === '<') return 真偽(c < 0);
      if (記 === '>') return 真偽(c > 0);
      if (記 === '<=') return 真偽(c <= 0);
      return 真偽(c >= 0);
    }

    var x = 数にする(左, 手); if (x.型 === '誤') return x;
    var y = 数にする(右, 手); if (y.型 === '誤') return y;
    if (記 === '+' || 記 === '-') {                                      /* ★②★ */
      var r2 = (記 === '+') ? (x.値 + y.値) : (x.値 - y.値);
      var c2 = 消え残りを消す(r2, x.値, y.値);
      if (c2 === r2) return 数(r2);
      /* ★ここでは 消さず ★印★ を 付ける★（上の 覚書き） */
      return { 型: '数', 値: r2, 消えたら: c2 };
    }
    if (記 === '*') return 数(x.値 * y.値);          /* ★丸めない★（③） */
    if (記 === '/') {
      if (y.値 === 0) return 誤('#DIV/0!');     /* ★実測 `=1/0` → #DIV/0!★ */
      return 数(x.値 / y.値);                     /* ★丸めない★（③） */
    }
    if (記 === '^') return 累乗(x.値, y.値);
    return 誤('#VALUE!');
  }

  /* ══ ★前に 付く ＋ − ★ ══
     ★＋ は 何も しません★（実測 `=+"1"` は ★字の まま★）
     ★− は 数に します★（実測 `=-"1"` → -1 ／ `=-D1` → 0） */
  function 前置き(記, 子, 手) {
    if (子.型 === '誤') return 子;
    if (記 === '+') return 子;
    var x = 数にする(子, 手); if (x.型 === '誤') return x;
    return 数(-x.値);
  }

  /* ══ ★後ろに 付く ％★ ══（実測 `=50%`→0.5 ／ `=3%`→0.03 ／ `=1%+1`→1.01） */
  function 後置き(記, 子, 手) {
    if (子.型 === '誤') return 子;
    if (記 !== '%') return 誤('#VALUE!');
    var x = 数にする(子, 手); if (x.型 === '誤') return x;
    return 数(x.値 / 100);
  }

  return {
    数: 数, 字: 字, 真偽: 真偽, 誤: 誤, 空: 空,
    つなぎ: つなぎ, 前置き: 前置き, 後置き: 後置き,
    数にする: 数にする, 字にする: 字にする,
    数を字に: 数を字に, 字を数に: 字を数に,
    打った数: 打った数, 累乗: 累乗, 並び: 並び,
    足し引きを締める: 足し引きを締める, 印を落とす: 印を落とす
  };
});
