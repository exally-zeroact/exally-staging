/* view-mode.js — ★ブックの表示（標準・改ページ プレビュー・ページ レイアウト）★ 2026-08-30
 *
 *  ★真値（実Excel 16.0 で 実測）★ … tools/measure-view.ps1 / tools/measure-margins.ps1
 *    ・Window.View … ★1=標準／2=改ページ プレビュー／3=ページ レイアウト★
 *    ・余白の既定 … 上下 1.905cm（54pt）／左右 1.778cm（50.4pt）／ヘッダー・フッター 21.6pt
 *    ・用紙 … A4（既定）。A4=21.0×29.7cm
 *    ・手で足す 改ページ … `HPageBreaks.Add(A20)` → ★その行（20）で 切れる★
 *    ・120行×20列を A4縦・既定で 刷ると 実Excel は ★1ページ 39行 × 8列★
 *      （切れ目が 40・79・118行目／9・17列目）
 *
 *  ★真似られない事（測って 分かった）★
 *    ★1ページに 何行 入るかは 印刷する機械（プリンタ）で 変わる★。
 *    A4の 大きさと 余白から 計算すると 41行 入るはずだが 実Excel は 39行だった
 *    ＝プリンタの「刷れない縁」のぶん。
 *    ⇒ ★うちは 紙の 大きさから 計算する★（41行になる）。実Excelの 39行との 差は
 *      ★ここに 書き残す★。★プレビューの 帯には「機械で 変わる」と 書く★。
 *
 *  ★点と cm★ … 1cm = 72/2.54 = 28.3464567 点
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.ViewMode = factory();
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  var 一cmの点 = 72 / 2.54;                   /* 28.3464567 */

  /* 用紙の 大きさ（cm）… 実Excelの 用紙番号は grid-print.js に 実測を 残してある */
  var 用紙たち = {
    A4:     { 名: 'A4',     幅: 21.0, 高: 29.7 },
    A3:     { 名: 'A3',     幅: 29.7, 高: 42.0 },
    A5:     { 名: 'A5',     幅: 14.8, 高: 21.0 },
    B5:     { 名: 'B5',     幅: 18.2, 高: 25.7 },
    Letter: { 名: 'Letter', 幅: 21.59, 高: 27.94 },
  };

  var 既定の余白 = { 上: 1.905, 下: 1.905, 左: 1.778, 右: 1.778 };   /* ★実測★ */

  var 表示たち = [
    { 番: 1, 名: '標準',               Excel: 'xlNormalView' },
    { 番: 2, 名: '改ページ プレビュー', Excel: 'xlPageBreakPreview' },
    { 番: 3, 名: 'ページ レイアウト',   Excel: 'xlPageLayoutView' },
  ];

  /** 紙の「字が 入る」大きさ（点）
   *  @param o {用紙,向き,余白,倍率}  向き='portrait'|'landscape'／倍率＝％（既定100）
   */
  function 紙の中身(o) {
    o = o || {};
    var 紙 = 用紙たち[o.用紙 || 'A4'] || 用紙たち.A4;
    var 余 = o.余白 || 既定の余白;
    var 横 = 紙.幅, 縦 = 紙.高;
    if (o.向き === 'landscape') { var t = 横; 横 = 縦; 縦 = t; }
    var 倍 = (o.倍率 === null || o.倍率 === undefined) ? 100 : Number(o.倍率);
    if (!isFinite(倍) || 倍 < 10) 倍 = 10;
    if (倍 > 400) 倍 = 400;
    return {
      幅: (横 - 余.左 - 余.右) * 一cmの点 * (100 / 倍),
      高: (縦 - 余.上 - 余.下) * 一cmの点 * (100 / 倍),
      紙: 紙.名,
    };
  }

  /** 切れ目を 数える（★手で足した 分を 混ぜる★）
   *  @param 大きさたち 1つずつの 大きさ（点）… 行なら 高さ・列なら 幅
   *  @param 入る       1ページに 入る 大きさ（点）
   *  @param 手で       手で 足した 切れ目（0 から 数えた 番号の 配列。★その 前で 切れる★）
   *  @returns 切れ目の 番号（0 から 数える。その 番号の 手前で 切れる）
   */
  function 切れ目(大きさたち, 入る, 手で) {
    var 出 = [];
    var 手 = {};
    for (var h = 0; h < (手で || []).length; h++) 手[手で[h]] = true;
    var 積 = 0;
    for (var i = 0; i < 大きさたち.length; i++) {
      if (手[i] && i > 0) { 出.push(i); 積 = 0; }        /* 手で 足した 所は そこで 切る */
      var d = 大きさたち[i];
      if (積 > 0 && 積 + d > 入る) { 出.push(i); 積 = 0; }
      積 += d;
      if (d >= 入る) { /* 1つで 1ページを 超える物は そのまま 1ページに する */ }
    }
    /* 同じ 番号を 2回 入れない（手で足した所と 自然に 切れる所が 重なる 事が 在る） */
    var 消し = [], 見た = {};
    for (var k = 0; k < 出.length; k++) { if (!見た[出[k]]) { 見た[出[k]] = true; 消し.push(出[k]); } }
    消し.sort(function (a, b) { return a - b; });
    return 消し;
  }

  /** ページの 数（行の切れ目 × 列の切れ目） */
  function ページ数(行の切れ目, 列の切れ目) {
    return (行の切れ目.length + 1) * (列の切れ目.length + 1);
  }

  /** 1ページ目に 入る 行数（切れ目が 無ければ 全部） */
  function 一ページの数(切れ目たち, 全部) {
    return 切れ目たち.length ? 切れ目たち[0] : 全部;
  }

  return {
    一cmの点: 一cmの点, 用紙たち: 用紙たち, 既定の余白: 既定の余白, 表示たち: 表示たち,
    紙の中身: 紙の中身, 切れ目: 切れ目, ページ数: ページ数, 一ページの数: 一ページの数,
  };
}));
