  const 作る = () => {
    const h = H.表();
    h.打つ('A1', '5');
    h.打つ('B1', '=A1*2');
    return h;
  };
  const 古いdata = { '0,0': { v: '5' }, '0,1': { f: '=A1*2' } };

  /* ★正しい 順★ ... 合わせる → その マスを 打つ */
  const h1 = 作る();
