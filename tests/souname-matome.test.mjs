/* souname-matome.test.mjs — ★総なめの まとめ（読む 側の 道具）が 赤を 出せるか★（2026-10-04）
 *
 *  ★なぜ★ ... 束が 途中で 切られた 出しを 「赤 0」と 見間違えかけた（10-04）。
 *    読む 側を 道具に した（scripts/souname-matome.mjs）。★その 道具が 本当に 赤を 出すか★を 見る。
 *  ★壊し方★ ＝ 経営者の 叩き ⑴〜⑸ ＋ Exally1 の 3通り
 *  走らせ方: node tests/souname-matome.test.mjs
 */
import { 判じる } from '../scripts/souname-matome.mjs';

let 緑 = 0, 赤 = 0;
const T = (n, ok, m) => {
  if (ok) { 緑++; console.log('  ok   ' + n); }
  else { 赤++; console.log('  NG   ' + n + (m ? '\n       ' + m : '')); }
};

/* ══ ★作り物★ ══（名簿 10本・束 2つ） */
const 回 = { 名札: 'aaaa', 頭: 'h1', 名簿の指紋: 'p1', 名簿: 10, 始めた: '2026-10-04T01:00:00.000Z' };
const 今 = { 頭: 'h1', 名簿の指紋: 'p1', 名簿: 10, 木: '' };
const 束 = (始, 終, 足し) => Object.assign({
  名札: 'aaaa', 頭: 'h1', 名簿の指紋: 'p1', 名簿: 10, 始, 終, 頼んだ: 終 - 始 + 1, 走らせた: 終 - 始 + 1,
  緑: 終 - 始 + 1, 赤: [], 始めた: '2026-10-04T01:01:00.000Z', 終えた: '2026-10-04T01:02:00.000Z', 前の木: '', 後の木: '',
}, 足し || {});
const clone = (o) => JSON.parse(JSON.stringify(o));

console.log('[souname-matome] ★まとめが 赤を 出せるか★');

const 素 = 判じる(回, [束(1, 6), 束(7, 10)], 今);
T('★全部 揃えば 緑★（名簿 10／覆った 10／緑 10）', !素.赤.length && 素.覆った === 10 && 素.緑 === 10, JSON.stringify(素));

const 組 = [
  ['★束の 記録が 1つ 無い（途中で 切られた）★', [束(1, 6)], 今, 回],
  ['★範囲に 隙間★', [束(1, 5), 束(7, 10)], 今, 回],
  ['★範囲が 重なる★', [束(1, 6), 束(6, 10)], 今, 回],
  ['★束の 頭が 古い★', [束(1, 6), 束(7, 10, { 頭: 'h0' })], 今, 回],
  ['★前の 回の 完走 記録が 残って いる（同じ 頭）★', [束(1, 6), 束(7, 10, { 名札: 'bbbb' })], 今, 回],
  ['★束の 後の 木が 汚れて いる★', [束(1, 6), 束(7, 10, { 後の木: ' M lib/x.js' })], 今, 回],
  ['★束の 前の 木が 汚れて いる★', [束(1, 6, { 前の木: '?? a.txt' }), 束(7, 10)], 今, 回],
  ['★名簿の 指紋が 違う（束）★', [束(1, 6), 束(7, 10, { 名簿の指紋: 'p9' })], 今, 回],
  ['★名簿の 指紋が 違う（今）★', [束(1, 6), 束(7, 10)], Object.assign(clone(今), { 名簿の指紋: 'p9' }), 回],
  ['★頼んだ ≠ 走らせた★', [束(1, 6), 束(7, 10, { 走らせた: 3 })], 今, 回],
  ['★束に 赤が 在る★', [束(1, 6), 束(7, 10, { 赤: ['8本目 x.test.mjs'], 緑: 3 })], 今, 回],
  ['★回の 札より 前に 始めた 束★', [束(1, 6), 束(7, 10, { 始めた: '2026-10-04T00:59:00.000Z' })], 今, 回],
  ['★今の 頭が 札と 違う★', [束(1, 6), 束(7, 10)], Object.assign(clone(今), { 頭: 'h2' }), 回],
  ['★今の 木が 空で ない★', [束(1, 6), 束(7, 10)], Object.assign(clone(今), { 木: ' M book.html' }), 回],
  ['★束の 記録を 読めない（半端）★', [束(1, 6), { 読めない: '束-7-10.json' }], 今, 回],
  ['★回の 札が 無い★', [束(1, 6), 束(7, 10)], 今, null],
];
for (const [名, 束たち, いま, 札] of 組) {
  const r = 判じる(札, 束たち, いま);
  T('赤に なる: ' + 名, r.赤.length > 0, '★緑に なって しまった★ ' + JSON.stringify(r));
}

console.log('\nsouname-matome: ' + 緑 + ' 緑 / ' + 赤 + ' 赤');
process.exit(赤 ? 1 : 0);
