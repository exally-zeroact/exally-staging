import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const require_ = createRequire(path.join(ROOT, 'package.json'));
const H = require_(path.join(ROOT, 'lib/shiki-hyou.js'));
const 自己 = process.argv.includes('--self-test');

let pass = 0, fail = 0;
const T = (n, f) => {
  try { f(); pass++; console.log('  ✓ ' + n); }
  catch (e) { fail++; console.log('  ✗ ' + n + ' — ' + e.message); }
};

/* ★1つずつ★ と ★まとめて★ で 同じ 打ち方を して、見る マスの 字を 比べる */
function 二通り(打ち方, 見る, 前に = null, 終わりを呼ぶ = true) {
  const 一 = H.表(), 束 = H.表();
  if (前に) { 前に(一); 前に(束); }
  for (const [名, 字] of 打ち方) 一.打つ(名, 字);
  束.まとめて打つ始め();
  for (const [名, 字] of 打ち方) 束.打つ(名, 字);
  if (終わりを呼ぶ) 束.まとめて打つ終わり();
  const 違う = [];
  for (const n of 見る) { const a = 一.字(n), b = 束.字(n); if (a !== b) 違う.push(n + ' 1つずつ=' + a + ' まとめ=' + b); }
  return 違う;
}
const 見せる = (違う) => { if (違う.length) throw new Error('★' + 違う.length + 'マス 違う★ ' + 違う.slice(0, 5).join(' ／ ')); };

console.log('\n[shiki-hyou-matomete] ★まとめて 打っても 1つずつ と 答えが 同じか★' + (自己 ? '（--self-test）' : ''));

if (自己) {
  /* ★わざと 壊す★＝答えが 入った 後の 打ち直しで 終わりを 呼ばない ⇒ 見ている 式に 古い 答えが 残る はず */
  const 前に = (h) => { h.打つ('A1', '1'); h.打つ('B1', '=A1*10'); h.打つ('C1', '=B1+1'); h.字('C1'); };
  const 違う = 二通り([['A1', '5']], ['A1', 'B1', 'C1'], 前に, false);
  T('★終わりを 呼び忘れると 古い 答えが 残って 違いが 出る★（違い ' + 違う.length + 'マス・B1 と C1 の 2 の はず）', () => {
    if (違う.length !== 2) throw new Error('違い ' + 違う.length + '（2 の はず）' + 違う.join(' ／ '));
  });
  console.log('\nshiki-hyou-matomete --self-test: ' + pass + ' 緑 / ' + fail + ' 赤');
  process.exit(fail ? 1 : 0);
}

T('① 逆順の 鎖（式 先・材料 後）', () => {
  const 打 = [];
  for (let i = 30; i >= 2; i--) 打.push(['A' + i, '=A' + (i - 1) + '+1']);
  打.push(['A1', '1']);
  const 見 = 打.map((x) => x[0]);
  見せる(二通り(打, 見));
});

T('② 菱形（M1=K1-Q1・Q1=K1*2）', () => {
  見せる(二通り([['M1', '=K1-Q1'], ['Q1', '=K1*2'], ['K1', '10']], ['K1', 'Q1', 'M1']));
});

T('③ 板またぎ（板1!A1＝板2!B1*2・板2!B1 は 後から）', () => {
  const 前に = (h) => { h.板('板1'); h.板('板2'); h.板('板1'); };
  見せる(二通り([['板1!A1', '=板2!B1*2'], ['板1!A2', '=SUM(板2!B1:B3)'], ['板2!B1', '3'], ['板2!B2', '4'], ['板2!B3', '5']],
    ['板1!A1', '板1!A2', '板2!B1'], 前に));
});

T('④ 溢れ（溢れを 見る 式を 先に 打つ）＝1つずつ も まとめて も 実Excel と 同じ（F1＝5）', () => {
  /* ★2026-10-05★ 前は 1つずつ 打つと F1 が ★0 の まま★だった（溢れで 埋まった マスを 見る 式を 直して いなかった）。
       `打つ` で その 間に 出来た 覆いを 見る 式を 直す 様に した ⇒ 両方 5（実Excel・経営者の 物差し 137 の 組 F） */
  const 打 = [['F1', '=E2+E3'], ['E1', '=A1:A3'], ['A1', '1'], ['A2', '2'], ['A3', '3']];
  見せる(二通り(打, ['E1', 'E2', 'E3', 'F1']));
  const 一 = H.表();
  for (const [名, 字] of 打) 一.打つ(名, 字);
  const 出 = ['E1', 'E2', 'E3', 'F1'].map((n) => 一.字(n)).join(',');
  if (出 !== '1,2,3,5') throw new Error('1つずつ E1,E2,E3,F1 が ' + 出 + '（実Excel 1,2,3,5）');
});

T('⑧ 塞いだ 物を 消すと 溢れが 戻る（実Excel 組 J＝1,2,3）・塞がって いる 間は #SPILL!（E2 は 9 の まま）', () => {
  /* ★2026-10-05★ 前は 塞いだ 9 を 消しても E1 は #SPILL! の まま（E1 は E2 を 頼って いない＝直されない） */
  const h = H.表();
  for (const [名, 字] of [['A1', '1'], ['A2', '2'], ['A3', '3'], ['F1', '=E3*10'], ['E2', '9'], ['E1', '=A1:A3']]) h.打つ(名, 字);
  const 塞 = ['E1', 'E2', 'E3', 'F1'].map((n) => h.字(n)).join(',');
  if (塞 !== '#SPILL!,9,,0') throw new Error('塞がって いる 間 E1,E2,E3,F1 が ' + 塞 + '（#SPILL!,9,,0 の はず）');
  h.打つ('E2', '');
  const 戻 = ['E1', 'E2', 'E3', 'F1'].map((n) => h.字(n)).join(',');
  if (戻 !== '1,2,3,30') throw new Error('消した 後 E1,E2,E3,F1 が ' + 戻 + '（1,2,3,30 の はず＝溢れを 見る F1 も 直る）');
});

