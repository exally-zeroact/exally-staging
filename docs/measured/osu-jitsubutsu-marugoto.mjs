/* osu-jitsubutsu-marugoto.mjs — ★司さんの 実物に 列まるごと（A:A）の 式が 何本 在るか★（2026-09-16）
 *
 *  ★★何の 為か★★
 *    棚66 … `=COUNT(A:A)` が ★0★ を 返す（★誤りでは なく 数★＝気づけない）
 *    ⇒★司さんの 本に 当たるか★を 先に 数える＝★急ぐか どうかの 判じ★
 *
 *  ★★決め（司さんの 実物・4つとも 守ります）★★
 *    ①★読むだけ＝1バイトも 書かない★（`触っていないか()` で 前後を 突き合わせ）
 *    ②★★出すのは 数だけ★★（★式も 板の 名前も 中身も 1文字も 出しません★）
 *    ③★紙を 書きません★＝画面に 出すだけ
 *    ④★本体だけ★（`本の道` は 1つ）
 *
 *  ★押し方は 書きません★ … `osu-jitsubutsu-dodai.mjs` を 呼ぶだけ
 *    （★別の 道を 作ると 印が 抜ける★）
 *
 *  ★★見て いない 事★★
 *    ・★名前で 定めた 範囲★が 列まるごとを 指して いる 形は 見て いません
 *    ・★この 本に 0本でも 「欠陥が 小さい」では ありません★
 *      ＝この 本は Excel の 面の 一部しか 使って いません
 *
 *  使い方: node docs/measured/osu-jitsubutsu-marugoto.mjs
 */
import { 本を開く, 触っていないか, 裸に } from './osu-jitsubutsu-dodai.mjs';

/* ★列まるごと★ … `A:A` `$A:$A` `AB:AB`（★両側とも 数字が 付かない★） */
const 列まるごと = /(^|[^A-Z0-9_$!.])\$?([A-Z]{1,3})\s*:\s*\$?([A-Z]{1,3})(?![A-Z0-9])/;
/* ★行まるごと★ … `1:1` `$1:$1`（★両側とも 数字だけ★） */
const 行まるごと = /(^|[^A-Z0-9_$!.])\$?([0-9]{1,7})\s*:\s*\$?([0-9]{1,7})(?![0-9])/;

const { wb, 前 } = await 本を開く();

let マス数 = 0, 式の数 = 0, 列本数 = 0, 行本数 = 0, 板数 = 0;
const 列の式 = new Set(), 行の式 = new Set();

for (const 板名 of wb.SheetNames) {
  const sh = wb.Sheets[板名];
  if (!sh || !sh['!ref']) continue;
  板数++;
  for (const k of Object.keys(sh)) {
    if (k.charAt(0) === '!') continue;
    const c = sh[k];
    if (!c) continue;
    マス数++;
    if (typeof c.f !== 'string' || !c.f) continue;
    式の数++;
    const 素 = 裸に(c.f);
    if (列まるごと.test(素)) { 列本数++; 列の式.add(素); }
    if (行まるごと.test(素)) { 行本数++; 行の式.add(素); }
  }
}

const 印 = 触っていないか(前);

console.log('');
console.log('★司さんの 実物＝★読むだけ★（書いて いません）★');
console.log('  ' + 印.字 + '（大きさ ' + 印.大きさ + 'バイト）');
console.log('');
console.log('★数えた 元★');
console.log('  板 … ' + 板数 + '枚 ／ 中身の 在る マス … ' + マス数 + '個 ／ 式の マス … ' + 式の数 + '個');
console.log('');
console.log('★★列まるごと（A:A）を 使う 式★★ … ' + 列本数 + '本（★通り数 ' + 列の式.size + '★）');
console.log('★★行まるごと（1:1）を 使う 式★★ … ' + 行本数 + '本（★通り数 ' + 行の式.size + '★）');
console.log('');
if (列本数 === 0 && 行本数 === 0) {
  console.log('⇒★この 本には 1本も 在りません★＝★この 本に 限れば 急ぎません★');
  console.log('  ★★「0本だから 欠陥が 小さい」では ありません★★');
  console.log('    ＝この 本は Excel の 面の 一部しか 使って いません');
} else {
  console.log('⇒★★在ります＝客に 出て いる 欠陥です★★');
}
console.log('');
console.log('★出したのは 数だけです★（式・板の 名前・中身は 1文字も 出して いません）');
