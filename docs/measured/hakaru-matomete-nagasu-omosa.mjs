import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const require_ = createRequire(path.join(ROOT, 'package.json'));
const H = require_(path.join(ROOT, 'lib/shiki-hyou.js'));

const 引数 = process.argv.slice(2);
const 取る = (名, 既定) => { const i = 引数.indexOf('--' + 名); return i >= 0 ? Number(引数[i + 1]) : 既定; };
const N = 取る('N', 2000);

/** ★まとめて 流す★＝本を 開いた 時と 同じ 形で 1マスずつ 打つ */
const 四角の幅 = 取る('幅', 100);
function 流す(N, 形) {
  const h = H.表();
  h.打つ('A1', '1');
  const t0 = process.hrtime.bigint();
  for (let i = 2; i <= N + 1; i++) {
    /* ⑴鎖 ･･･ 前の マスを 見る（★本の 合計の 形★）
       ⑵扇 ･･･ 全部が A1 を 見る */
    /* ⑶★四角★ ･･･ `=SUM(A1:A<幅>)`（★実物の 式は これ★）
         ＝★1本で 何百マスも 見ます★＝`頼りを拾う` が 範囲を 名前に 開きます
         ＝経営者1 の 実測 ･･･ `四角を読む` 2,051,000回 ／ `読む揃った名で` 62,578,562回 */
    var 式;
    if (形 === '鎖') 式 = '=A' + (i - 1) + '+1';
    else if (形 === '扇') 式 = '=A1+1';
    else 式 = '=SUM(A1:A' + Math.min(i - 1, 四角の幅) + ')';
    h.打つ('A' + i, 式);
  }
  const t1 = process.hrtime.bigint();
  /* ★最後の 答えを 1つ 読みます★＝★流しただけで 計算して いない のでは ない事を 見る★ */
  const 最後 = h.字('A' + (N + 1));
  return { ms: Number(t1 - t0) / 1e6, 最後: 最後 };
}

