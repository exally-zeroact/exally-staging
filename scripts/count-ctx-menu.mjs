export function うち() {
  const src = fs.readFileSync(path.join(ROOT, 'lib/ctx-menu.js'), 'utf8');
  const mod = { exports: {} };
  new Function('module', 'exports', src)(mod, mod.exports);
  const 出 = [];
  (function 歩く(a) {
    for (const v of (a || [])) {
      if (v.名) 出.push(v);
      else if (v.穴 && 穴の橋[v.穴]) 出.push({ 名: 穴の橋[v.穴], 穴: v.穴 });
      if (v.子) 歩く(v.子);
    }
  })(mod.exports.表 || []);
  return 出;
}

export function 数える() {
  const 我 = うち();
  const 当たり = new Map();          // 実Excel の 字 → うちの 札
  const 帯 = [], 独自 = [], 未測定 = [], 子 = [];
  for (const v of 我) {
    const 橋 = 名前の橋[v.名];
    if (橋) { if (!当たり.has(橋)) 当たり.set(橋, []); 当たり.get(橋).push(v.名); continue; }
    if (行や列の帯から.indexOf(v.名) >= 0) { 帯.push(v.名); continue; }
    if (子の橋[v.名]) { 子.push(v.名); continue; }
    if (条件つき未測定.indexOf(v.名) >= 0) { 未測定.push(v.名); continue; }
    独自.push(v.名);
  }
  const 残り = 実Excelの20.filter((r) => !当たり.has(r.字));
  const 足りない = 残り.filter((r) => !作らない[r.字])
    .map((r) => r.字 + (r.印 ? '【' + r.印 + '】' : ''));
  const 作らない分 = 残り.filter((r) => 作らない[r.字]).map((r) => r.字);
  const 子の分母 = Object.keys(実Excelの子).reduce((n, k) => n + 実Excelの子[k].length, 0);
  return { 我, 当たり, 帯, 独自, 子, 未測定, 足りない, 作らない分,
    分母: 実Excelの20.length, 子の分母 };
}

