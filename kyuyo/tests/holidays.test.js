/* holidays.test.js — 国民の祝日 自前計算＋所定労働日数 */
'use strict';
var H = require('../lib/holidays.js');

/* 令和8年(2026)の祝日 — 固定/ハッピーマンデー/春分秋分/振替/国民の休日 */
T('2026 祝日一覧(振替・国民の休日込み)', function () {
  var y = H.holidaysOfYear(2026);
  eq(y['2026-01-01'], '元日');
  eq(y['2026-01-12'], '成人の日');      // 1月第2月曜
  eq(y['2026-02-11'], '建国記念の日');
  eq(y['2026-02-23'], '天皇誕生日');
  eq(y['2026-03-20'], '春分の日');
  eq(y['2026-04-29'], '昭和の日');
  eq(y['2026-05-03'], '憲法記念日');     // 日曜
  eq(y['2026-05-04'], 'みどりの日');
  eq(y['2026-05-05'], 'こどもの日');
  eq(y['2026-05-06'], '振替休日');       // 5/3(日)の振替が5/4・5/5(祝)を飛ばして5/6へ
  eq(y['2026-07-20'], '海の日');         // 7月第3月曜
  eq(y['2026-08-11'], '山の日');
  eq(y['2026-09-21'], '敬老の日');       // 9月第3月曜
  eq(y['2026-09-22'], '国民の休日');     // 敬老(21)と秋分(23)に挟まれた平日
  eq(y['2026-09-23'], '秋分の日');
  eq(y['2026-10-12'], 'スポーツの日');   // 10月第2月曜
  eq(y['2026-11-03'], '文化の日');
  eq(y['2026-11-23'], '勤労感謝の日');
});

T('春分/秋分の近似式(2026=3/20・9/23)', function () {
  eq(H.shunbun(2026), 20); eq(H.shubun(2026), 23);
  eq(H.shunbun(2025), 20); eq(H.shubun(2025), 23); // 2025も妥当
});

T('holidaysInMonth: 2026-05は5件(3/4/5/6)', function () {
  var m = H.holidaysInMonth('2026-05');
  eq(m.length, 4); // 5/3,5/4,5/5,5/6
  eq(m[0].day, 3); eq(m[3].day, 6); eq(m[3].name, '振替休日');
});

/* 所定労働日数 = 暦日 − 休みの曜日 − 祝日 − 会社独自休 */
T('所定労働日数 2026-01 土日休=20日(31−週末9−祝日2)', function () {
  eq(H.scheduledWorkdays('2026-01', [0, 6], []), 20);
});
T('所定労働日数 2026-05 土日休(祝日と振替を除外)', function () {
  // 5月2026: 31日。土:2,9,16,23,30(5) 日:3,10,17,24,31(5)=週末10。祝日で平日のもの=5/4(月),5/5(火),5/6(水・振替)=3。31−10−3=18
  eq(H.scheduledWorkdays('2026-05', [0, 6], []), 18);
});
T('会社独自休を差し引く', function () {
  var base = H.scheduledWorkdays('2026-06', [0, 6], []);
  var withCo = H.scheduledWorkdays('2026-06', [0, 6], ['2026-06-15']); // 6/15(月)は平日
  eq(withCo, base - 1);
});
T('日曜だけ休み(現場系・週休1日)は所定が多い', function () {
  ok(H.scheduledWorkdays('2026-01', [0], []) > H.scheduledWorkdays('2026-01', [0, 6], []));
});

/* scheduledWorkdaysBetween: [startYmd,endYmd]∩当月 の所定労働日数(産休/育休の不就労日算定用)。
   2026-06は6/1=月・土日休・祝日なし=所定22日。 */
T('範囲内所定 2026-06 6/15〜6/30=12日(産休後半・土日休)', function () {
  eq(H.scheduledWorkdaysBetween('2026-06', [0, 6], [], '2026-06-15', '2026-06-30'), 12);
});
T('範囲内所定: 全月を覆う範囲=scheduledWorkdaysと一致(22)', function () {
  eq(H.scheduledWorkdaysBetween('2026-06', [0, 6], [], '2026-05-01', '2026-07-31'), 22);
  eq(H.scheduledWorkdays('2026-06', [0, 6], []), 22);
});
T('範囲内所定: 月頭からの範囲は1日からclip(6/1〜6/14=10日)', function () {
  eq(H.scheduledWorkdaysBetween('2026-06', [0, 6], [], '2026-06-01', '2026-06-14'), 10); // 22−12
});
T('範囲内所定: 範囲が当月外=0', function () {
  eq(H.scheduledWorkdaysBetween('2026-06', [0, 6], [], '2026-07-01', '2026-07-31'), 0);
  eq(H.scheduledWorkdaysBetween('2026-06', [0, 6], [], '2026-04-01', '2026-05-31'), 0);
});
T('範囲内所定: 会社独自休を範囲内で除外(6/15平日を休に→11)', function () {
  eq(H.scheduledWorkdaysBetween('2026-06', [0, 6], ['2026-06-15'], '2026-06-15', '2026-06-30'), 11);
});
T('範囲内所定: 日付未設定/空=0(安全側)', function () {
  eq(H.scheduledWorkdaysBetween('2026-06', [0, 6], [], '', ''), 0);
  eq(H.scheduledWorkdaysBetween('2026-06', [0, 6], [], null, null), 0);
});
